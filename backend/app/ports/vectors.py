from typing import Protocol


class VectorStore(Protocol):
    def add(self, ids: list[str], documents: list[str], embeddings: list[list[float]], metadatas: list[dict]) -> None: ...
    def query(self, course_id: int, query: str, limit: int) -> list[dict]: ...
    def delete_by_material(self, course_id: int, material_id: int) -> None: ...
    def delete_by_course(self, course_id: int) -> None: ...
    def count(self) -> int: ...
